function fig(n, page, orig, cz, en) {
  const where = page ? { cz: `obr. ${n}, s. ${page}`, en: `Fig. ${n}, p. ${page}`, de: `Fig. ${n}, S. ${page}` } : { cz: `obr. ${n}, skládací příloha`, en: `Fig. ${n}, fold-out`, de: `Fig. ${n}, Faltblatt` };
  return {
    kind: 'book',
    tag: { cz: `Příručka 1936 · obr. ${n}`, en: `1936 manual · Fig. ${n}`, de: `Handbuch 1936 · Fig. ${n}` },
    orig: `Fig. ${n}  ${orig}`,
    cz, en,
    credit: { cz: `${HB.cz}, ${where.cz}. ${SCAN.cz}`, en: `${HB.en}, ${where.en}. ${SCAN.en}`, de: `${HB.de}, ${where.de}. ${SCAN.de}` },
  };
}
function photo(tagCz, tagEn, author, license, url, cz, en) {
  return {
    kind: 'photo',
    tag: { cz: tagCz, en: tagEn, de: TAG_DE[tagEn] ?? tagEn },
    cz, en,
    credit: { cz: `Foto: ${author}, ${license}, Wikimedia Commons.`, en: `Photo: ${author}, ${license}, Wikimedia Commons.`, de: `Foto: ${author}, ${license}, Wikimedia Commons.` },
    url,
  };
}

